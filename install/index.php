$step = max(1, min(4, (int) ($_GET['step'] ?? $_POST['step'] ?? 1)));
$errors = [];
$success = null;

function vaultora_boot_session_install(): void
{
    if (session_status() !== PHP_SESSION_ACTIVE) {
        session_name(VAULTORA_SESSION_NAME);
        session_start();
    }
}

function vaultora_check_requirements(): array
{
    $checks = [];
    $checks[] = ['label' => 'PHP 8.3+', 'ok' => version_compare(PHP_VERSION, '8.3.0', '>='), 'detail' => 'Current: ' . PHP_VERSION];
    foreach (['pdo', 'pdo_mysql', 'mbstring', 'fileinfo', 'json', 'session'] as $ext) {
        $checks[] = ['label' => 'Extension: ' . $ext, 'ok' => extension_loaded($ext), 'detail' => extension_loaded($ext) ? 'Loaded' : 'Missing'];
    }
    $checks[] = ['label' => 'ZipArchive (optional, for shared folder ZIP)', 'ok' => class_exists('ZipArchive'), 'detail' => class_exists('ZipArchive') ? 'Available' : 'Missing — folder ZIP disabled', 'optional' => true];

    $writable = [
        VAULTORA_ROOT . '/config',
        VAULTORA_ROOT . '/storage',
    ];
    foreach ($writable as $path) {
        if (!is_dir($path)) {
            @mkdir($path, 0755, true);
        }
        $checks[] = [
            'label' => 'Writable: ' . basename(dirname($path)) . '/' . basename($path),
            'ok' => is_dir($path) && is_writable($path),
            'detail' => $path,
        ];
    }

    $allRequired = true;
    foreach ($checks as $c) {
        if (empty($c['optional']) && !$c['ok']) {
            $allRequired = false;
            break;
        }
    }

    return ['checks' => $checks, 'ok' => $allRequired];
}

function vaultora_run_schema(PDO $pdo): void
{
    $sql = file_get_contents(__DIR__ . '/schema.sql');
    if ($sql === false) {
        throw new RuntimeException('Schema file missing.');
    }
    $pdo->exec($sql);
}

function vaultora_write_database_config(array $cfg): void
{
    $export = var_export([
        'host' => $cfg['host'],
        'port' => $cfg['port'],
        'name' => $cfg['name'],
        'user' => $cfg['user'],
        'pass' => $cfg['pass'],
        'charset' => 'utf8mb4',
    ], true);

    $content = "<?php\n/**\n * Vaultora — Database credentials (generated by installer)\n */\n\ndeclare(strict_types=1);\n\nreturn {$export};\n";
    if (file_put_contents(VAULTORA_ROOT . '/config/database.php', $content) === false) {
        throw new RuntimeException('Could not write database configuration.');
    }
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if ($step === 2) {
        $req = vaultora_check_requirements();
        if (!$req['ok']) {
            $errors[] = 'Resolve required environment checks before continuing.';
        } else {
            header('Location: ?step=3');
            exit;
        }
    }

    if ($step === 3) {
        $cfg = [
            'host' => trim((string) ($_POST['db_host'] ?? '127.0.0.1')),
            'port' => trim((string) ($_POST['db_port'] ?? '3306')),
            'name' => trim((string) ($_POST['db_name'] ?? 'vaultora_db')),
            'user' => trim((string) ($_POST['db_user'] ?? 'root')),
            'pass' => (string) ($_POST['db_pass'] ?? ''),
            'charset' => 'utf8mb4',
        ];

        try {
            // cPanel shared hosting: database usually already exists; CREATE may be denied
            try {
                $pdo = vaultora_db_connect_raw($cfg, true);
            } catch (Throwable) {
                $pdo = vaultora_db_connect_raw($cfg, false);
                try {
                    $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . str_replace('`', '``', $cfg['name']) . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
                } catch (Throwable) {
                    // Ignore create errors on restricted hosts
                }
                $pdo->exec('USE `' . str_replace('`', '``', $cfg['name']) . '`');
            }
            vaultora_run_schema($pdo);
            vaultora_write_database_config($cfg);
            $_SESSION['vaultora_install_db'] = true;
            header('Location: ?step=4');
            exit;
        } catch (Throwable $e) {
            $errors[] = 'Database setup failed: ' . $e->getMessage();
        }
    }

    if ($step === 4) {
        if (empty($_SESSION['vaultora_install_db'])) {
            $errors[] = 'Complete the database step first.';
            $step = 3;
        } else {
            $name = trim((string) ($_POST['admin_name'] ?? ''));
            $email = strtolower(trim((string) ($_POST['admin_email'] ?? '')));
            $pass = (string) ($_POST['admin_password'] ?? '');
            $pass2 = (string) ($_POST['admin_password_confirm'] ?? '');
            $appName = trim((string) ($_POST['app_name'] ?? 'Vaultora'));

            if ($name === '' || !filter_var($email, FILTER_VALIDATE_EMAIL)) {
                $errors[] = 'Enter a valid administrator name and email.';
            }
            if (strlen($pass) < 8) {
                $errors[] = 'Administrator password must be at least 8 characters.';
            }
            if ($pass !== $pass2) {
                $errors[] = 'Password confirmation does not match.';
            }

            if (!$errors) {
                try {
                    require_once dirname(__DIR__) . '/includes/settings.php';
                    require_once dirname(__DIR__) . '/includes/storage.php';
                    require_once dirname(__DIR__) . '/includes/activity.php';
                    require_once dirname(__DIR__) . '/includes/csrf.php';
                    require_once dirname(__DIR__) . '/includes/auth.php';

                    $pdo = vaultora_db();
                    $hash = password_hash($pass, PASSWORD_DEFAULT);
                    $quota = VAULTORA_DEFAULT_QUOTA;

                    $stmt = $pdo->prepare(
                        'INSERT INTO vault_users (email, password_hash, display_name, role, status, storage_quota_bytes, storage_used_bytes, created_at, updated_at)
                         VALUES (?, ?, ?, ?, ?, ?, 0, NOW(), NOW())'
                    );
                    $stmt->execute([$email, $hash, $name, 'admin', 'active', $quota * 2]);

                    $defaults = [
                        'app_name' => $appName !== '' ? $appName : 'Vaultora',
                        'max_upload_bytes' => (string) VAULTORA_DEFAULT_MAX_UPLOAD,
                        'default_quota_bytes' => (string) VAULTORA_DEFAULT_QUOTA,
                        'trash_retention_days' => (string) VAULTORA_DEFAULT_TRASH_DAYS,
                        'allowed_extensions' => implode(',', VAULTORA_DEFAULT_ALLOWED_EXTENSIONS),
                    ];
                    $ins = $pdo->prepare(
                        'INSERT INTO vault_settings (setting_key, setting_value, updated_at) VALUES (?, ?, NOW())
                         ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value), updated_at = NOW()'
                    );
                    foreach ($defaults as $k => $v) {
                        $ins->execute([$k, $v]);
                    }

                    vaultora_ensure_storage_dirs();
                    $adminId = (int) $pdo->lastInsertId();
                    vaultora_user_storage_dir($adminId);

                    file_put_contents(VAULTORA_LOCK_FILE, date('c') . "\nVaultora installed\n");
                    unset($_SESSION['vaultora_install_db']);

                    header('Location: ' . vaultora_url('admin/login.php?installed=1'));
                    exit;
                } catch (Throwable $e) {
                    $errors[] = 'Final setup failed: ' . $e->getMessage();
                }
            }
        }
    }
}

